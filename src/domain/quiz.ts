/** Приоритет при равенстве баллов: сначала состояния, требующие внимания. */
const TIE_ORDER: ProfileId[] = ['storm', 'desert', 'fog', 'harbor'];

export function scoreQuiz(answers: number[]): { profile: ProfileId; scores: Record<ProfileId, number> } {
  const scores: Record<ProfileId, number> = { storm: 0, desert: 0, fog: 0, harbor: 0 };
  answers.forEach((optionIndex, qi) => {
    const option = QUIZ[qi]?.options[optionIndex];
    if (option) scores[option.profile] += 1;
  });
  let best: ProfileId = TIE_ORDER[0]!;
  for (const p of TIE_ORDER) if (scores[p] > scores[best]) best = p;
  return { profile: best, scores };
}

export function isValidAnswers(answers: unknown): answers is number[] {
  return (
    Array.isArray(answers) &&
    answers.length === QUIZ.length &&
    answers.every((a, i) => Number.isInteger(a) && a >= 0 && a < (QUIZ[i]?.options.length ?? 0))
  );
}

